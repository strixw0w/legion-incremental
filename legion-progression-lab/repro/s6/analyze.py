def sens(name):
    rs = rows(name)
    if not rs:
        return None
    base = [r for r in rs if r['factor'] == 'baseline']
    bexp = mean([(snap(r['run'], 'D7') or {}).get('legionExp') for r in base])
    bclr = q([r['run']['milestones']['worldCleared']['activeMs'] / H if 'worldCleared' in r['run']['milestones'] else INF for r in base], 0.5)
    out = {'baseline': {'meanD7LegionExp': bexp, 'medianClearActiveH': fin(bclr)}, 'cells': []}
    for f in sorted({r['factor'] for r in rs} - {'baseline'}):
        for m in sorted({r['multiplier'] for r in rs if r['factor'] == f}):
            c = [r for r in rs if r['factor'] == f and r['multiplier'] == m]
            e = mean([(snap(r['run'], 'D7') or {}).get('legionExp') for r in c])
            cl = q([r['run']['milestones']['worldCleared']['activeMs'] / H if 'worldCleared' in r['run']['milestones'] else INF for r in c], 0.5)
            er = ratio(e, bexp)
            cr = None if math.isinf(cl) or math.isinf(bclr) else cl / bclr
            out['cells'].append({'factor': f, 'multiplier': m, 'runs': len(c), 'expRatio': er, 'clearRatio': cr, 'medianClearActiveH': fin(cl), 'notCleared': sum(1 for r in c if 'worldCleared' not in r['run']['milestones']),
                                 'expElasticity': None if er is None or er <= 0 else math.log(er) / math.log(m), 'clearElasticity': None if cr is None else math.log(cr) / math.log(m)})
    return out


