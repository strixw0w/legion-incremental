def runinfo(name):
    p = os.path.join(RES, name, 'run.json')
    return json.load(open(p, encoding='utf-8')) if os.path.exists(p) else None


def q(vals, p):
    """Linear-interpolation quantile (numpy's default); infinite values sort last."""
    v = sorted(vals)
    if not v:
        return None
    k = (len(v) - 1) * p
    f, c = math.floor(k), math.ceil(k)
    if f == c or v[c] == v[f]:
        return v[f]
    if math.isinf(v[c]):
        return INF
    return v[f] + (v[c] - v[f]) * (k - f)


def mean(vals):
    v = [x for x in vals if x is not None]
    return statistics.fmean(v) if v else None


def fin(x, nd=3):
    if x is None:
        return None
    if isinstance(x, float) and math.isinf(x):
        return None
    return round(x, nd) if isinstance(x, float) else x


def F(x, spec):
    """A number for the Markdown tables; a dash where it is missing or infinite."""
    if x is None or (isinstance(x, float) and (math.isinf(x) or math.isnan(x))):
        return '—'
    return format(x, spec)


def ratio(a, b):
    return None if a is None or b in (None, 0) else a / b


def snap(run, name):
    return run['snapshots'].get(name)


def last_snap(run, upto='D7'):
    order = ['5min', '1h', 'D1', 'D3', 'D7', 'D14', 'D30']
    best = None
    for k in order[: order.index(upto) + 1]:
        if k in run['snapshots']:
            best = run['snapshots'][k]
    return best


def stall(run):
    return max(run['longestStallActiveMin'], run.get('openStallActiveMin') or 0)


