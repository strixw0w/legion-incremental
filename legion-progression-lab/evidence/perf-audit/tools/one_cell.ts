/** Profiling probe: one S4 job in-process (same content loading as exp4.ts, no fingerprint checks). */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const LABP = fileURLToPath(new URL('../../../', import.meta.url));
const imp = (p: string) => import(new URL(`../../../${p}`, import.meta.url).href);
const { compileIndustryContent } = await imp('src/model/industryContent.ts');
const { compilePermanentContent } = await imp('src/model/permanentContent.ts');
const { S4ManifestSchema } = await imp('src/experiments/s4Manifest.ts');
const { runS4Job } = await imp('src/experiments/s4Jobs.ts');
const { patchS4Variant } = await imp('src/experiments/s4Patch.ts');
const { readJson } = await imp('src/cli/paths.ts');
const { readS1Pack } = await imp('src/cli/s1-content.ts');
const [manifestRel, cellId, repStr] = process.argv.slice(2);
const manifest = S4ManifestSchema.parse(JSON.parse(readFileSync(resolve(LABP, manifestRel as string), 'utf8')));
const perm = readJson(resolve(LABP, manifest.contentRef.path));
const ind = readJson(resolve(LABP, perm.basePack.path));
const leg = readJson(resolve(LABP, ind.basePack.path));
const base = readS1Pack(leg.basePack.path);
const index = readJson(resolve(LABP, 'content/tables/xp-sweep.index.json'));
const sweep = index.tables.map((t: { path: string }) => ({ ...t, json: readJson(resolve(LABP, t.path)) }));
const cellIndex = manifest.cells.findIndex((c: { id: string }) => c.id === cellId);
const cell = manifest.cells[cellIndex];
const v = manifest.variants.find((x: { id: string }) => x.id === cell.variant);
const t0 = performance.now();
const p = patchS4Variant(base, leg, ind, perm, v.params, sweep);
const content = compilePermanentContent(compileIndustryContent(p.base, p.table, p.legion, p.industry), p.industry, p.permanent);
const t1 = performance.now();
const rep = Number(repStr ?? 0);
const r = runS4Job({ cellIndex, replicate: rep, seedRoot: `${manifest.seeds.root}#rep-${rep}`, cell, ledger: 'persistent' }, content);
const t2 = performance.now();
const mem = process.memoryUsage();
console.log(JSON.stringify({ cell: cellId, compileMs: Math.round(t1 - t0), runMs: Math.round(t2 - t1), heapUsedMb: Math.round(mem.heapUsed / 2 ** 20), rssMb: Math.round(mem.rss / 2 ** 20), keys: Object.keys(r).slice(0, 8) }));
